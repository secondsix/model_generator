import re
from pathlib import Path


def is_modbus_file(path):
    return "modbus" in Path(path).stem.lower()


def convert_modbus_address(raw, comment, device_file):
    """资料优先于 WinCC 显示地址，返回地址和可选提示。"""
    raw = str(raw).strip()
    converted = ""
    match = re.fullmatch(r"3x(4\d{5})", raw, re.I)
    if match:
        offset = int(match.group(1)) - 400001
        if 0 <= offset <= 65535:
            converted = f"HR{offset}"
    else:
        # WinCC 0x 是线圈区标记，后面的数字是十进制一基地址。
        match = re.fullmatch(r"0x(\d+)(?:\.0)?", raw, re.I)
        if match:
            offset = int(match.group(1)) - 1
            if 0 <= offset <= 65535:
                converted = f"CO{offset}"
    stem = Path(device_file).stem.upper()
    if "ZS00990" in stem or "D21" in stem:
        key = re.sub(r"\s+", "", comment)
        if key == "实际熔胶时间":
            return "", "实际熔胶时间：D21资料包含1544和1574两个不同地址，请核实后填写"
        reference = D21_ADDRESSES.get(key)
        if reference:
            function, offset = reference
            authoritative = ("HR" if function == 3 else "CO") + str(offset)
            warning = ""
            if authoritative != converted:
                warning = f"{comment}：{raw} 按D21资料修正为 {authoritative}（通用换算为 {converted or '无法解析'}）"
            return authoritative, warning
    return converted, ""

